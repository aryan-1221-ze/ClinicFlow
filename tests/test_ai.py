def test_clinical_enquiry_is_not_sent_and_flagged(monkeypatch, post_json):
    monkeypatch.setenv("ANTHROPIC_API_KEY", "fake")
    monkeypatch.setattr(ai_service, "_call_llm", lambda *a: pytest.fail("LLM must not be called"))
    for route in ("categorize", "respond"):
        data = post_json(f"/assistant/{route}", {"enquiry": "I have chest pain and a fever, what dose should I take?"}).get_json()
        assert data["category"] == "Human assistance required"
        assert data["fallback_reason"] == "clinical_content"
        assert "NOT sent to an AI service" in data["notices"][0]
    assert "dose" not in data["text"].lower().replace("doctor", "")


