def test_live_respond_restores_clinic_contact_details_locally(monkeypatch, post_json):
    sent = {}

    def fake(system, user):
        sent["user"] = user
        return '{"category": "Opening hours or location", "draft": "Call us on [CONTACT_1]. Thanks."}'
    monkeypatch.setenv("OPENAI_API_KEY", "fake")
    monkeypatch.setattr(ai_service, "_call_llm", fake)
    data = post_json("/assistant/respond", {"enquiry": "Mail me at jane@example.org or 555 123 4567",
                                            "facts": "Reception phone: +91 44 1234 5678"}).get_json()
    assert "jane@example.org" not in sent["user"] and "555 123 4567" not in sent["user"]
    assert "+91 44 1234 5678" not in sent["user"]          # contact data never leaves the server
    assert "+91 44 1234 5678" in data["text"]              # but is restored in the local draft
    assert data["source"] == "llm" and "OpenAI" in data["label"]


