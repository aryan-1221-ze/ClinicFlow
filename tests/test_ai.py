def test_assistant_input_validation(post_json, client):
    assert post_json("/assistant/categorize", {"enquiry": "   "}).status_code == 422
    assert post_json("/assistant/categorize", {"enquiry": "x" * 1001}).status_code == 422
    assert post_json("/assistant/respond", {"enquiry": "hi", "facts": "x" * 1001}).status_code == 422
    assert post_json("/assistant/appointment-message", {"appointment_id": "abc", "kind": "reminder"}).status_code == 422
    assert post_json("/assistant/appointment-message", {"appointment_id": 1, "kind": "wrong"}).status_code == 422
    assert post_json("/assistant/appointment-message", {"appointment_id": 999, "kind": "reminder"}).status_code == 422
    assert client.post("/assistant/categorize", data="not json", content_type="text/plain",
                       headers={"X-CSRF-Token": "bad"}).status_code == 400


